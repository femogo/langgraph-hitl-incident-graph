KNOWN_SERVICES = ("payment-api", "auth-service", "inventory-db")

DIAGNOSE_SYSTEM_PROMPT = (
    "You are an SRE Diagnostic Subagent. Investigate the reported incident using ONLY "
    "the provided read-only MCP inspection tools (list_services, get_service_status, "
    "get_service_logs). Check the affected service status and recent logs, then provide "
    "a concise technical diagnosis identifying the service name, root cause, and key metrics."
)

REMEDIATION_SYSTEM_PROMPT = (
    "You are an SRE Remediation Planner. Based on the verified diagnostic findings, "
    "select the safest, most effective remediation action from: "
    "'rollback_deployment' (for bad deployments / post-deploy errors), "
    "'restart_service' (for transient memory leaks / high resource pressure), or "
    "'scale_service' (for high traffic / CPU load). "
    "Do not invent service names; use the exact diagnosed service."
)


class RemediationProposal(BaseModel):
    """Structured remediation plan generated by the LLM before HITL approval."""

    tool: Literal["restart_service", "scale_service", "rollback_deployment"] = Field(
        description="Name of the MCP write tool to execute upon human approval."
    )
    service_name: str = Field(
        description="Exact name of the target service (e.g., 'payment-api')."
    )
    replicas: int | None = Field(
        default=None,
        description="Target replica count (required only when tool is 'scale_service').",
    )
    reason: str = Field(
        description="Clear justification referencing the diagnostic metrics or logs."
    )

    def to_action_dict(self) -> dict[str, Any]:
        args: dict[str, Any] = {"service_name": self.service_name}
        if self.tool == "scale_service":
            args["replicas"] = self.replicas if self.replicas is not None else 4
        return {
            "tool": self.tool,
            "args": args,
            "reason": self.reason,
        }


def get_chat_model() -> ChatOllama:
    """Instantiate the configured local Ollama chat model."""
    settings = get_settings()
    return ChatOllama(
        model=settings.ollama_model,
        base_url=settings.ollama_base_url,
        temperature=0,
    )


def _detect_service_in_text(text: str) -> str | None:
    lowered = text.lower()
    for svc in KNOWN_SERVICES:
        if svc in lowered:
            return svc
    return None


def _thread_id_from_config(config: RunnableConfig | None) -> str:
    if not config:
        return "default"
    configurable = config.get("configurable") or {}
    return str(configurable.get("thread_id") or "default")


def supervisor_node(state: IncidentState) -> dict[str, Any]:
    """Supervisor orchestrator that evaluates state before routing to specialized subagents."""
    if not state.get("incident_summary"):
        return {"resolution_status": "investigating"}
    return {}


def route_from_supervisor(
    state: IncidentState,
) -> Literal["diagnose_agent", "remediation_planner", "__end__"]:
    """Route dynamically based on current investigation and approval lifecycle."""
    status = state.get("resolution_status", "investigating")
    if status in {"resolved", "aborted"}:
        return "__end__"
    if not state.get("incident_summary"):
        return "diagnose_agent"
    if not state.get("proposed_action"):
        return "remediation_planner"
    return "__end__"


def _make_diagnose_node(llm: BaseChatModel, read_tools: list[Any]):
    tools_by_name = {tool.name: tool for tool in read_tools}
    bound_llm = llm.bind_tools(read_tools)

    async def diagnose_agent_node(state: IncidentState) -> dict[str, Any]:
        conversation: list[BaseMessage] = [
            SystemMessage(content=DIAGNOSE_SYSTEM_PROMPT),
            *state["messages"],
        ]
        new_messages: list[BaseMessage] = []
        final_diagnosis = ""

        for _ in range(5):
            ai_msg = await bound_llm.ainvoke(conversation)
            conversation.append(ai_msg)
            new_messages.append(ai_msg)

            tool_calls = getattr(ai_msg, "tool_calls", None) or []
            if not tool_calls:
                final_diagnosis = str(ai_msg.content).strip()
                break

            for tc in tool_calls:
                t_name = str(tc["name"])
                t_args = dict(tc.get("args") or {})
                t_id = str(tc.get("id") or t_name)
                tool = tools_by_name.get(t_name)
                if tool is None:
                    output = json.dumps({"error": f"Read tool '{t_name}' is not permitted."})
                else:
                    output = str(await tool.ainvoke(t_args))

                tool_msg = ToolMessage(content=output, tool_call_id=t_id, name=t_name)
                conversation.append(tool_msg)
                new_messages.append(tool_msg)

        if not final_diagnosis:
            final_diagnosis = "Diagnostic inspection completed; review tool outputs above."

        combined_text = "\n".join(
            [final_diagnosis, *(str(m.content) for m in new_messages)]
        )
        target = state.get("target_service") or _detect_service_in_text(combined_text)

        return {
            "messages": new_messages,
            "target_service": target,
            "incident_summary": final_diagnosis,
            "resolution_status": "investigating",
        }

    return diagnose_agent_node


def _make_remediation_planner_node(
    llm: BaseChatModel,
    guardrails: ActionGuardrails,
    audit_logger: AuditLogger,
):
    structured_llm = llm.with_structured_output(RemediationProposal)

    async def remediation_planner_node(
        state: IncidentState,
        config: RunnableConfig,
    ) -> dict[str, Any]:
        thread_id = _thread_id_from_config(config)
        summary = state.get("incident_summary", "")
        target = state.get("target_service") or "unknown-service"
        prompt_messages: list[BaseMessage] = [
            SystemMessage(content=REMEDIATION_SYSTEM_PROMPT),
            HumanMessage(
                content=(
                    f"Target service hint: {target}\n"
                    f"Diagnostic summary:\n{summary}\n\n"
                    "Produce the structured remediation proposal."
                )
            ),
        ]
        proposal_obj: RemediationProposal = await structured_llm.ainvoke(prompt_messages)  # type: ignore[assignment]
        proposal = proposal_obj.to_action_dict()
        service_name = proposal["args"]["service_name"]

        audit_logger.log_event(
            event="PROPOSED",
            thread_id=thread_id,
            service=service_name,
            tool=proposal["tool"],
            args=proposal["args"],
            actor="planner",
            details={"reason": proposal["reason"]},
        )

        verdict = guardrails.validate(
            tool=proposal["tool"],
            args=proposal["args"],
            thread_id=thread_id,
        )
        if not verdict.allowed:
            audit_logger.log_event(
                event="GUARDRAIL_BLOCKED",
                thread_id=thread_id,
                service=service_name,
                tool=proposal["tool"],
                args=proposal["args"],
                actor="guardrail",
                details={"rule": verdict.rule, "reason": verdict.reason, "stage": "pre_approval"},
            )
            blocked_reply = AIMessage(
                content=(
                    f"[Guardrail Blocked] Proposal '{proposal['tool']}' on '{service_name}' "
                    f"violated policy ({verdict.rule}): {verdict.reason}"
                )
            )
            return {
                "messages": [blocked_reply],
                "target_service": service_name,
                "proposed_action": None,
                "resolution_status": "aborted",
            }

        reply = AIMessage(
            content=(
                f"[Proposal] Recommended '{proposal['tool']}' on '{service_name}' "
                f"({proposal['reason']}). Awaiting human operator approval."
            )
        )
        return {
            "messages": [reply],
            "target_service": service_name,
            "proposed_action": proposal,
            "resolution_status": "awaiting_approval",
        }

    return remediation_planner_node


def _make_human_approval_node(audit_logger: AuditLogger):
    def human_approval_node(state: IncidentState, config: RunnableConfig) -> dict[str, Any]:
        """Pause execution via interrupt() until an operator approves or rejects proposed_action."""
        proposed = state.get("proposed_action")
        if not proposed:
            return {}

        thread_id = _thread_id_from_config(config)
        service_name = str(proposed.get("args", {}).get("service_name") or state.get("target_service"))

        decision = interrupt(
            {
                "type": "remediation_approval",
                "target_service": state.get("target_service"),
                "proposed_action": proposed,
                "instructions": "Resume with Command(resume={'approved': True/False, 'note': '...'})",
            }
        )

        if isinstance(decision, dict):
            approved = bool(decision.get("approved", False))
            note = str(decision.get("note", "")).strip()
        else:
            approved = bool(decision)
            note = ""

        suffix = f" Note: {note}" if note else ""
        if approved:
            audit_logger.log_event(
                event="APPROVED",
                thread_id=thread_id,
                service=service_name,
                tool=str(proposed["tool"]),
                args=dict(proposed.get("args") or {}),
                actor="human",
                details={"note": note},
            )
            return {
                "messages": [
                    AIMessage(content=f"[HITL] Operator APPROVED '{proposed['tool']}'.{suffix}")
                ],
                "resolution_status": "awaiting_approval",
            }

        audit_logger.log_event(
            event="REJECTED",
            thread_id=thread_id,
            service=service_name,
            tool=str(proposed["tool"]),
            args=dict(proposed.get("args") or {}),
            actor="human",
            details={"note": note},
        )
        return {
            "messages": [
                AIMessage(content=f"[HITL] Operator REJECTED '{proposed['tool']}'.{suffix}")
            ],
            "resolution_status": "aborted",
        }

    return human_approval_node


def route_after_approval(
    state: IncidentState,
) -> Literal["execute_remediation", "abort_remediation", "__end__"]:
    """Route approved proposals to live MCP execution or rejected ones to abort."""
    if not state.get("proposed_action"):
        return "__end__"
    if state.get("resolution_status") == "aborted":
        return "abort_remediation"
    return "execute_remediation"


def _make_live_execute_node(
    session: ClientSession,
    guardrails: ActionGuardrails,
    audit_logger: AuditLogger,
):
    async def execute_remediation_node(
        state: IncidentState,
        config: RunnableConfig,
    ) -> dict[str, Any]:
        proposed = state.get("proposed_action")
        if not proposed:
            return {"resolution_status": "aborted"}

        thread_id = _thread_id_from_config(config)
        tool_name = str(proposed["tool"])
        args = dict(proposed.get("args") or {})
        service_name = str(args.get("service_name") or state.get("target_service") or "")

        # Defense-in-depth guardrail check right before mutating infrastructure
        verdict = guardrails.validate(tool=tool_name, args=args, thread_id=thread_id)
        if not verdict.allowed:
            audit_logger.log_event(
                event="GUARDRAIL_BLOCKED",
                thread_id=thread_id,
                service=service_name,
                tool=tool_name,
                args=args,
                actor="guardrail",
                details={"rule": verdict.rule, "reason": verdict.reason, "stage": "pre_execution"},
            )
            return {
                "messages": [
                    AIMessage(
                        content=(
                            f"[Guardrail Blocked] Execution of '{tool_name}' on '{service_name}' "
                            f"aborted ({verdict.rule}): {verdict.reason}"
                        )
                    )
                ],
                "proposed_action": None,
                "resolution_status": "aborted",
            }

        try:
            raw_result = await call_mcp_tool(session, tool_name, args)
        except Exception as exc:
            audit_logger.log_event(
                event="EXECUTION_FAILED",
                thread_id=thread_id,
                service=service_name,
                tool=tool_name,
                args=args,
                actor="executor",
                details={"error": str(exc)},
            )
            raise

        guardrails.record_execution(tool=tool_name, args=args, thread_id=thread_id)
        audit_logger.log_event(
            event="EXECUTED",
            thread_id=thread_id,
            service=service_name,
            tool=tool_name,
            args=args,
            actor="executor",
            details={"result": str(raw_result)},
        )

        reply = AIMessage(
            content=f"[Remediation] Executed MCP tool '{tool_name}': {raw_result}"
        )
        return {
            "messages": [reply],
            "proposed_action": None,
            "resolution_status": "resolved",
        }

    return execute_remediation_node


def abort_remediation_node(state: IncidentState) -> dict[str, Any]:
    """Close the incident cleanly without invoking MCP write tools."""
    proposed = state.get("proposed_action") or {}
    tool_name = proposed.get("tool", "unknown_action")
    reply = AIMessage(
        content=f"[Aborted] Cancelled '{tool_name}'. Infrastructure left untouched."
    )
    return {
        "messages": [reply],
        "proposed_action": None,
        "resolution_status": "aborted",
    }


async def build_supervisor_graph(
    session: ClientSession,
    llm: BaseChatModel | None = None,
    checkpointer: BaseCheckpointSaver[Any] | None = None,
    guardrails: ActionGuardrails | None = None,
    audit_logger: AuditLogger | None = None,
) -> CompiledStateGraph[Any]:
    """Compile the Supervisor multi-agent graph wired to live MCP tools, guardrails, and audit log."""
    active_llm = llm or get_chat_model()
    active_guardrails = guardrails or ActionGuardrails()
    active_audit = audit_logger or AuditLogger()
    read_tools, _write_tools = await load_mcp_tool_groups(session)

    builder = StateGraph(IncidentState)
    builder.add_node("supervisor", supervisor_node)
    builder.add_node("diagnose_agent", _make_diagnose_node(active_llm, read_tools))
    builder.add_node(
        "remediation_planner",
        _make_remediation_planner_node(active_llm, active_guardrails, active_audit),
    )
    builder.add_node("human_approval", _make_human_approval_node(active_audit))
    builder.add_node(
        "execute_remediation",
        _make_live_execute_node(session, active_guardrails, active_audit),
    )
    builder.add_node("abort_remediation", abort_remediation_node)

    builder.add_edge(START, "supervisor")
    builder.add_conditional_edges(
        "supervisor",
        route_from_supervisor,
        {
            "diagnose_agent": "diagnose_agent",
            "remediation_planner": "remediation_planner",
            "__end__": END,
        },
    )
    builder.add_edge("diagnose_agent", "supervisor")
    builder.add_edge("remediation_planner", "human_approval")
    builder.add_conditional_edges(
        "human_approval",
        route_after_approval,
        {
            "execute_remediation": "execute_remediation",
            "abort_remediation": "abort_remediation",
            "__end__": END,
        },
    )
    builder.add_edge("execute_remediation", END)
    builder.add_edge("abort_remediation", END)

    return builder.compile(checkpointer=checkpointer)


async def run_live_incident_turn(
    report: str,
    thread_id: str = "live-incident-1",
    db_path: str | Path = ".incident_checkpoints.sqlite",
    infra_state_path: Path | None = None,
    llm: BaseChatModel | None = None,
    guardrails: ActionGuardrails | None = None,
    audit_log_path: str | Path = ".incident_audit.jsonl",
) -> dict[str, Any]:
    """Run an incident report against the live stdio MCP server and async SQLite checkpointer."""
    config = {"configurable": {"thread_id": thread_id}}
    audit_logger = AuditLogger(audit_log_path)
    async with (
        open_mcp_stdio_session(infra_state_path=infra_state_path) as session,
        open_async_sqlite_checkpointer(db_path) as checkpointer,
    ):
        graph = await build_supervisor_graph(
            session=session,
            llm=llm,
            checkpointer=checkpointer,
            guardrails=guardrails,
            audit_logger=audit_logger,
        )
        return await graph.ainvoke(
            initial_incident_state(HumanMessage(content=report)),
            config=config,
        )
